package com.fo.addon.mixin;

import com.fo.addon.elytra.hell.HellFlightRuntime;
import net.minecraft.client.render.RenderTickCounter;
import org.objectweb.asm.Opcodes;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Shadow;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfoReturnable;

@Mixin(RenderTickCounter.Dynamic.class)
public abstract class HellFlightTimerMixin {
    @Shadow
    private float dynamicDeltaTicks;

    @Inject(method = "beginRenderTick(J)I", at = @At(value = "FIELD", target = "Lnet/minecraft/client/render/RenderTickCounter$Dynamic;lastTimeMillis:J", opcode = Opcodes.PUTFIELD))
    private void fo$scaleTick(long timeMillis, CallbackInfoReturnable<Integer> cir) {
        if (HellFlightRuntime.isActive()) dynamicDeltaTicks *= HellFlightRuntime.timerMultiplier();
    }
}
